ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "github-pages"
UPLOADS = ROOT / "upload"


def safe_slug(value: str, fallback: str = "story") -> str:
    value = re.sub(r"[^a-z0-9]+", "-", str(value or "").lower()).strip("-")
    return value or fallback


def as_datetime(value):
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    if isinstance(value, str):
        try:
            return datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            pass
    return None


def display_date(value) -> str:
    date = as_datetime(value)
    if not date:
        return ""
    return date.astimezone().strftime("%b %d, %Y · %I:%M %p").replace(" 0", " ")


def static_image_url(value, from_post: bool = False) -> str:
    """Copy local Flask uploads into the static site and return a relative URL."""
    raw = str(value or "").strip()
    if not raw:
        return ""
    match = re.match(r"^/?upload/([^/?#]+)", raw)
    if not match:
        return raw

    filename = Path(match.group(1)).name
    source = UPLOADS / filename
    target = OUTPUT / "upload" / filename
    if source.exists() and source.is_file():
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
    prefix = "../" if from_post else ""
    return f"{prefix}upload/{filename}"


def rewrite_markdown_images(source: str) -> str:
    def replace(match):
        alt, url = match.group(1), match.group(2)
        return f"![{alt}]({static_image_url(url, from_post=True)})"

    return re.sub(r"!\[([^\]]*)\]\(([^)\s]+)", replace, source or "")


def esc(value) -> str:
    return html.escape(str(value or ""), quote=True)


def public_url(path: str) -> str:
    """Turn an exported relative asset/page path into a shareable absolute URL."""
    raw = str(path or "").strip()
    if raw.startswith("http://") or raw.startswith("https://"):
        return raw
    base = os.getenv("PUBLIC_SITE_URL", "https://adityasonar29.github.io/Blog_Post").rstrip("/")
    return f"{base}/{raw.lstrip('./')}"


def post_slug(post: dict, used: set[str]) -> str:
    base = safe_slug(post.get("slug") or post.get("title"))
    candidate = base
    suffix = 2
    while candidate in used:
        candidate = f"{base}-{suffix}"
        suffix += 1
    used.add(candidate)
    return candidate


